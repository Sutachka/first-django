def home(request):
    posts_list = list(ARTICLES.values())
    return render(request, 'blog/home.html', {'posts': posts_list})


def about(request):
    return render(request, 'blog/about.html')


def post_detail(request, post_id):
    post = ARTICLES.get(post_id)
    if not post:
        raise Http404("Такой статьи пока нет на космической орбите нашего блога!")
    return render(request, 'blog/post_detail.html', {'post': post})


def feedback(request):
    feedbacks = Feedback.objects.filter(is_checked=True).order_by('-id')

    if request.method == 'POST':
        form = FeedbackForm(request.POST)
        if form.is_valid():
            form.save()
            return redirect('feedback')
    else:
        form = FeedbackForm()

    return render(request, 'blog/feedback.html', {
        'feedbacks': feedbacks,
        'form': form
    })